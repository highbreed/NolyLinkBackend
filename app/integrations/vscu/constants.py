"""VSCU resultCd table.

Two genuinely different sources feed one response envelope, since the local VSCU app either
answers a request itself or deserializes whatever real KRA sent back verbatim
(`VsdcUtil.jsonToObject(resStr, ...)` in every *Excute controller — confirmed by decompiling
vscu-v2.0.21.jar with CFR, 2026-09-01):

- LOCAL_RESULT_CODES: generated by the local VSCU app's own Java code, before or instead of
  ever calling KRA. Verified present in the decompiled source (`grep setResultCd`) across
  com/kra/vsdc/excute/*.java.
- Everything else success/error-shaped that can come back (000, 001, 891-899, 900-903,
  910-912, 921-922, 990-995, 999) is real KRA's own OSCU-style envelope, passed through
  unmodified — see app/services/kra_adapter.py's raise_for_result for that table; VSCU reuses
  it exactly since the local app never rewrites a KRA-originated resultCd (only ever
  overwrites its own synthetic ones, e.g. 894 -> 000 on offline signing — see
  TrnsSalesExcute.saveTrnsSales).

Not included: two codes (824, 838) that a since-superseded planning document assumed existed.
Neither appears anywhere in the decompiled jar, nor in KRA's own published OSCU result-code
table. Omitted rather than guessed (see app/integrations/vscu/exceptions.py's module
docstring) — if a live device ever returns one, VSCUError's fallback path handles it as an
unrecognized code rather than crashing.
"""

